# Findings:
# Image captions are indexed and retrieved exactly like text chunks — the
# retriever does not need to know whether content came from text or an image.
# The quarterly revenue query retrieves the bar chart (image) as rank 1 —
# this information exists only in the chart, not in any text chunk.
# The manufacturing query retrieves only the world map image — this data
# is entirely visual and would be missed by text-only RAG.
