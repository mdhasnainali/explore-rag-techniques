#
# Standard retrieval (embed query directly):
#   [score=0.312] Photosynthesis is the process by which plants convert sunlight into glucose...
#   [score=0.289] Chlorophyll is the green pigment in plants that absorbs light energy...
#   [score=0.241] Cellular respiration breaks down glucose to release ATP energy in mitochondria.
#
# HyDE retrieval (embed hypothetical answer):
#   [score=0.812] Photosynthesis is the process by which plants convert sunlight into glucose...
#   [score=0.756] Chlorophyll is the green pigment in plants that absorbs light energy...
#   [score=0.701] The light-dependent reactions of photosynthesis occur in the thylakoid membranes.

# Findings:
# HyDE scores are dramatically higher (0.81 vs 0.31) because the hypothetical
# answer uses the same vocabulary as the documents ("photosynthesis", "chlorophyll",
# "thylakoid", "Calvin cycle"). The short query "How do plants make food?" uses
# none of those terms.
# HyDE also changes the rank-3 result: standard retrieval surfaces "cellular
# respiration" (wrong topic), HyDE surfaces "light-dependent reactions" (correct).
# The risk: if the LLM generates a wrong hypothetical answer, retrieval drifts
# toward incorrect documents. Always ground the final answer in retrieved docs,
# not in the hypothetical answer itself.
